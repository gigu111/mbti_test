/** 유형마다 짝지어진 3D 동물 캐릭터의 기본 정보입니다. */
export interface CharacterInfo {
  /** 캐릭터의 동물 종류 (예: "부엉이") */
  animal: string;
  /** 동물과 성격에 어울리게 지은 캐릭터 이름 */
  name: string;
}

/** 16가지 MBTI 유형 하나에 대한 전체 설명 데이터 구조입니다. */
export interface MbtiTypeProfile {
  /** 4글자 MBTI 유형 코드 (예: "ENFP") */
  code: MbtiType;
  /** 유형의 매력을 담은 한글 별명 */
  nickname: string;
  /** 결과를 보자마자 특징이 떠오르는 한 줄 소개 */
  summary: string;
  /** 성격의 핵심 모습을 풀어서 전하는 3~4문장 설명 */
  description: string;
  /** 이 유형이 빛나는 강점 3가지 */
  strengths: [string, string, string];
  /** 함께 신경 쓰면 더 좋아지는 조심할 점 2가지 */
  cautions: [string, string];
  /** 서로 시너지가 잘 나는 유형 코드 2개 */
  compatibleTypes: [MbtiType, MbtiType];
  /** 결과 카드와 캐릭터 분위기에 어울리는 파스텔 톤 대표 색상(HEX) */
  color: string;
  /** 이 유형을 대표하는 동물 캐릭터 정보 */
  character: CharacterInfo;
}

